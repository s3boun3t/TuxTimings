#!/usr/bin/env bash
# One build identity for executable, UI, diagnostic reports and packages.
set -euo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)"
version=$(tr -d '\r\n' < "$root/VERSION")
[[ $version =~ ^[0-9][0-9A-Za-z.+~]*$ ]] || { echo 'Invalid VERSION' >&2; exit 1; }
profile=${TUXTIMINGS_BUILD_PROFILE:-portable}
[[ $profile == portable || $profile == native ]] || { echo "Invalid build profile" >&2; exit 1; }
revision=unknown
state=archive
if command -v git >/dev/null && [[ $(git -C "$root" rev-parse --show-toplevel 2>/dev/null || true) == "$root" ]]; then
    revision=$(git -C "$root" rev-parse --short=12 HEAD)
    count=$(git -C "$root" rev-list --count HEAD)
    state=clean
    [[ -z $(git -C "$root" status --porcelain --untracked-files=all) ]] || state=dirty
    version+="+git.$count.g$revision"
    [[ $state == clean ]] || version+='.dirty'
else
    version+='+archive'
fi
identity="TuxTimings $version (revision $revision, $state, $profile)"
manifest() {
    printf 'Build: %s\nVersion: %s\nRevision: %s\nSource state: %s\nProfile: %s\n' "$identity" "$version" "$revision" "$state" "$profile"
}
case ${1:---id} in
    --id) printf '%s\n' "$identity" ;;
    --version) printf '%s\n' "$version" ;;
    --manifest) manifest ;;
    --generate)
        [[ $# == 2 && -n $2 ]] || exit 2
        mkdir -p -- "$2"
        header=$(mktemp "$2/build-info.XXXXXX")
        info=$(mktemp "$2/build-info.XXXXXX")
        trap 'rm -f -- "$header" "$info"' EXIT
        cat > "$header" <<EOF
/* Generated by tools/build-info.sh. */
#define TUXTIMINGS_BUILD_VERSION "$version"
#define TUXTIMINGS_BUILD_REVISION "$revision"
#define TUXTIMINGS_BUILD_STATE "$state"
#define TUXTIMINGS_BUILD_PROFILE "$profile"
#define TUXTIMINGS_BUILD_ID "$identity"
EOF
        manifest > "$info"
        cmp -s "$header" "$2/build_info.generated.h" || mv -- "$header" "$2/build_info.generated.h"
        cmp -s "$info" "$2/build-info.txt" || mv -- "$info" "$2/build-info.txt"
        chmod 644 -- "$2/build_info.generated.h" "$2/build-info.txt"
        ;;
    *) echo "Usage: $0 [--id|--version|--manifest|--generate DIRECTORY]" >&2; exit 2 ;;
esac
